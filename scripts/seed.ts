// Builds supabase/seed.sql from the sample CSVs. Run: npm run seed (then `supabase db reset` applies it).
import { writeFileSync } from "node:fs";
import { loadSampleSnapshot } from "../lib/csv.ts";
import { TABLES } from "../lib/tables.ts";

const jsonb = new Set(["sequence", "sent", "drafts"]);
const sql = (v: unknown, column: string): string =>
  v === null ? "null"
  : jsonb.has(column) ? `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`
  : Array.isArray(v) ? `'{${v.map((x) => JSON.stringify(String(x))).join(",")}}'`
  : typeof v === "string" ? `'${v.replaceAll("'", "''")}'`
  : String(v);

const snapshot = loadSampleSnapshot();
const tables = (Object.keys(TABLES) as (keyof typeof TABLES)[]).filter((t) => snapshot[t].length); // in foreign-key order
const statements = tables.map((t) => {
  const rows = snapshot[t] as Record<string, unknown>[];
  const columns = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${columns.map((c) => sql(r[c], c)).join(", ")})`).join(",\n");
  return `insert into ${TABLES[t]} (${columns.join(", ")}) values\n${values};`;
});

writeFileSync("supabase/seed.sql", `-- Generated by scripts/seed.ts from the sample CSVs. Do not edit by hand.\n\n${statements.join("\n\n")}\n`);
console.log(`Wrote supabase/seed.sql (${tables.length} tables)`);
